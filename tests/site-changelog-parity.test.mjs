test('CAR-131 site (CAR-132 pagination): the split pages carry the release count of their root source', { skip: NO_PAGINATED_MIRRORS }, () => {
  const mirrors = join(ROOT, 'site', 'src', 'content', 'changelog');
  const bad = [];
  for (const lang of ['en', ...LOCALES]) {
    const src = join(ROOT, lang === 'en' ? 'CHANGELOG.md' : `CHANGELOG.${lang}.md`);
    const pages = readdirSync(mirrors)
      .filter((f) => f.startsWith(`${lang}-p`) && f.endsWith('.md'))
      .sort();
    if (pages.length === 0) {
      bad.push(`${lang}: no paginated mirrors (<lang>-pNN.md) on disk — run the site sync`);
      continue;
    }
    const nSrc = countReleases(readFileSync(src, 'utf8'));
    const nPages = pages.reduce((sum, f) => sum + countReleases(readFileSync(join(mirrors, f), 'utf8')), 0);
    if (nPages !== nSrc) bad.push(`${lang}: ${pages.length} pages carry ${nPages} vs root ${nSrc}`);
  }
  assert.deepEqual(bad, [], `paginated mirrors out of sync with root: ${bad.join(', ')}`);
});

