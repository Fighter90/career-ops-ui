import { chromium } from 'playwright';
const BASE = 'https://resumecraft.ru';
const AUTH = `Basic ${Buffer.from(`${process.env.AUTH_LOGIN}:${process.env.AUTH_PASSWORD}`).toString('base64')}`;
const H = { Authorization: AUTH };
let pass = 0, fail = 0;
const ok = (n, c, e = '') => { if (c) { pass++; console.log(`  ok  ${n}`); } else { fail++; console.log(`FAIL  ${n} ${e}`); } };
const j = async (p) => (await fetch(BASE + p, { headers: H })).json();
const code = async (p) => (await fetch(BASE + p, { headers: H })).status;
const health = await j('/api/health');
ok('health.ok', health.ok === true);
ok('version 1.253.0', health.version === '1.254.0', health.version);
ok('parentVersion 1.38.0', health.parentVersion === '1.38.0', health.parentVersion);
ok('tracker 200', (await code('/api/tracker')) === 200);
ok('reports 200', (await code('/api/reports')) === 200);
ok('config 200', (await code('/api/config')) === 200);
ok('activity 200', (await code('/api/activity')) === 200);
const shell = await fetch(BASE + '/', { headers: H });
ok('GET / 200', shell.status === 200);
ok('CSP no unsafe-inline script', (shell.headers.get('content-security-policy') || '').includes("script-src 'self'"));
const js = (await shell.text()).match(/src="(\/js\/[^"]+\.js)"/)?.[1];
ok('bundle 200', js ? (await code(js)) === 200 : false);
const b = await chromium.launch();
const page = await b.newPage({ httpCredentials: { username: process.env.AUTH_LOGIN, password: process.env.AUTH_PASSWORD } });
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto(BASE + '/#/dashboard', { waitUntil: 'commit' });
await page.waitForFunction(() => window.API && (document.getElementById('footer-version')?.textContent || '').includes('v1.'), null, { timeout: 90000 });
await page.waitForFunction(() => { const t = document.getElementById('content')?.innerText || ''; return t.length > 100 && !t.includes('Loading'); }, null, { timeout: 90000 });
ok('dashboard renders', (await page.locator('#content').innerText().catch(() => '')).length > 100);
await page.goto(BASE + '/#/tracker', { waitUntil: 'commit' });
await page.waitForFunction(() => { const t = document.getElementById('content')?.innerText || ''; return t.length > 100 && !t.includes('Loading'); }, null, { timeout: 60000 });
ok('tracker renders', (await page.locator('#content').innerText().catch(() => '')).length > 100);
ok('no page errors', errs.length === 0, errs[0] || '');
await b.close();
console.log(`${pass}/${pass + fail} passed`);
process.exit(fail ? 1 : 0);
